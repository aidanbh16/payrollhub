import { z } from "zod";

// Every secret, key location, and connection string comes from the environment.
// Each layer adds its variables here as it is built; see .env.example.

/** The Redis password that .env.example and the README used to print (RT-05): every install knew it. */
const PUBLISHED_REDIS_PASSWORD = "dev-only-redis-password-change-me";
const redisPassword = (url: string) => decodeURIComponent(new URL(url).password);

/** Loopback hosts only: service tokens sent to INTERNAL_API_ORIGIN must never leave this machine (DV-36). */
function isLoopbackOrigin(value: string): boolean {
  const host = new URL(value).hostname;
  return host === "localhost" || host === "[::1]" || /^127(\.\d{1,3}){3}$/.test(host);
}

const envSchema = z.object({
  DATABASE_PATH: z.string().min(1),
  // Generated per install by npm run setup (RT-05); the formerly published development password is refused.
  REDIS_URL: z
    .url({ protocol: /^rediss?$/ })
    .refine((url) => redisPassword(url) !== PUBLISHED_REDIS_PASSWORD, "must not use the published placeholder password (run npm run setup)"),
  // AES-256-GCM key for bank fields, TOTP secrets, and ACH file bodies: 32 random bytes, base64.
  FIELD_ENCRYPTION_KEY: z
    .string()
    .refine((v) => Buffer.from(v, "base64").length === 32, "must be 32 bytes, base64-encoded (run npm run setup)"),
  // Stand-in tenant IdP (D11): its signing keys and user directory. Not part of PayrollHub's own data.
  MOCK_IDP_DIR: z.string().min(1).default(".data/mock-idp"),
  // Stand-in for employees' email (D13): mailboxes for confirmation links and notices. Not part of PayrollHub's data.
  MOCK_MAIL_DIR: z.string().min(1).default(".data/mock-mail"),
  // Development credentials for testers (staff passwords, TOTP secrets and otpauth links, IdP passwords, random
  // mailbox passwords), written by npm run db:reset (gitignored, owner-only). See scripts/lib/dev-credentials.ts.
  DEV_CREDENTIALS_FILE: z.string().min(1).default(".data/dev-credentials.txt"),
  // Local certificate authority and mTLS certificates for the stand-in bank (D12), generated by npm run setup.
  PKI_DIR: z.string().min(1).default(".data/pki"),
  // The stand-in originating bank (D12): where ACH Disbursement sends signed batches over mTLS, and its own data.
  BANK_URL: z.url({ protocol: /^https$/ }).default("https://localhost:8443"),
  BANK_TIMEOUT_MS: z.coerce.number().int().min(100).max(120_000).default(10_000),
  MOCK_BANK_DIR: z.string().min(1).default(".data/mock-bank"),
  // Central log pipeline (Section 2.5; D14): redacted, structured, append-only log files.
  LOG_DIR: z.string().min(1).default(".data/logs"),
  // Local key store (DV-07): versioned signing keys, created by npm run db:reset.
  KEYSTORE_DIR: z.string().min(1).default(".data/keys"),
  // Edge rate limiter (Section 2.2). Leave TRUSTED_CLIENT_IP_HEADER unset unless a reverse proxy in front of the app
  // overwrites that header with the real client address: Next.js itself gives Proxy no unforgeable client IP.
  TRUSTED_CLIENT_IP_HEADER: z.string().regex(/^[a-z0-9-]+$/).optional(),
  RATE_LIMIT_PREFIX: z.string().regex(/^[a-zA-Z0-9:_-]+$/).default("rl"),
  // Where the application layer reaches its own /api/internal/* routes. Configured, never taken from the request's
  // Host header, and it must be a loopback address, so service tokens cannot be sent off the machine (DV-36).
  INTERNAL_API_ORIGIN: z
    .url({ protocol: /^https?$/ })
    .default("http://127.0.0.1:3000")
    .refine(isLoopbackOrigin, "must be a loopback address (127.x.x.x, localhost, or [::1])"),
  // Public origin used in links sent to employees (bank-change confirmation emails).
  APP_ORIGIN: z.url({ protocol: /^https?$/ }).default("http://localhost:3000"),
});

export type Env = z.infer<typeof envSchema>;

/** Validates an environment. Errors name the variables (and the rule broken), never their values. */
export function parseEnv(source: Record<string, string | undefined>): Env {
  const parsed = envSchema.safeParse(source);
  if (!parsed.success) {
    const problems = [...new Set(parsed.error.issues.map((i) => `${i.path.join(".")}${i.message.startsWith("must") ? ` (${i.message})` : ""}`))];
    throw new Error(`Invalid or missing environment variables: ${problems.join(", ")}. Run npm run setup; see .env.example.`);
  }
  return parsed.data;
}

let cached: Env | undefined;

export function env(): Env {
  cached ??= parseEnv(process.env);
  return cached;
}
