import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { generateSync } from "otplib";
import { env } from "@/config/env";

// The development credentials file (DEV_CREDENTIALS_FILE, default .data/dev-credentials.txt; gitignored, owner-only).
// npm run db:reset writes it, so a tester can sign in with nothing but the README and this file:
//   staff     organization, email, role, password, TOTP secret, and an otpauth:// link for an authenticator app
//             (npm run totp -- <email> prints the current code instead);
//   employee  organization, email, and the stand-in IdP password;
//   mailbox   the random per-install mailbox password for /dev/outbox (D30).
// One record per line, tab-separated, with # comment lines explaining each section.

export interface StaffCredential {
  organization: string;
  email: string;
  role: string;
  password: string;
  totpSecret: string;
  otpauth: string;
}

interface Records {
  staff: StaffCredential[];
  employees: { organization: string; email: string; idpPassword: string }[];
  mailboxes: { address: string; password: string }[];
}

export function otpauthLink(organization: string, email: string, secret: string): string {
  const label = encodeURIComponent(`PayrollHub (${organization}):${email}`);
  return `otpauth://totp/${label}?secret=${secret}&issuer=PayrollHub&algorithm=SHA1&digits=6&period=30`;
}

export function writeDevCredentials(records: Records): void {
  const file = env().DEV_CREDENTIALS_FILE;
  mkdirSync(dirname(file), { recursive: true });
  const lines = [
    "# PayrollHub development credentials, generated by npm run db:reset for this install. Gitignored: never commit.",
    "# One record per line; fields are separated by tabs.",
    "#",
    "# Staff: sign in at /login with organization, email, and password, then a 6-digit code.",
    "#   Current code: npm run totp -- <email>     Or add the otpauth:// link to an authenticator app.",
    "# staff\torganization\temail\trole\tpassword\tTOTP secret\totpauth link",
    ...records.staff.map((s) => ["staff", s.organization, s.email, s.role, s.password, s.totpSecret, s.otpauth].join("\t")),
    "#",
    "# Employees: at /login enter the organization under \"Employees\", then sign in at the organization's stand-in IdP.",
    "# employee\torganization\temail\tIdP password",
    ...records.employees.map((e) => ["employee", e.organization, e.email, e.idpPassword].join("\t")),
    "#",
    "# Mailboxes at /dev/outbox: the stand-in for each person's own email (D13). Random per install (D30).",
    "# mailbox\taddress\tpassword",
    ...records.mailboxes.map((m) => ["mailbox", m.address, m.password].join("\t")),
    "",
  ];
  writeFileSync(file, lines.join("\n"), { mode: 0o600 });
}

function records(kind: string): string[][] {
  let text: string;
  try {
    text = readFileSync(env().DEV_CREDENTIALS_FILE, "utf8");
  } catch {
    throw new Error(`No development credentials file at ${env().DEV_CREDENTIALS_FILE}. Run npm run db:reset.`);
  }
  return text
    .split("\n")
    .map((l) => l.split("\t"))
    .filter((f) => f[0] === kind);
}

export function readStaffCredential(email: string): StaffCredential {
  const f = records("staff").find((r) => r[2] === email.trim().toLowerCase());
  if (!f) throw new Error(`No staff account ${email} in the development credentials file.`);
  return { organization: f[1], email: f[2], role: f[3], password: f[4], totpSecret: f[5], otpauth: f[6] };
}

/** An employee's password at the tenant's stand-in IdP (D22). */
export function idpPasswordFor(email: string): string {
  const f = records("employee").find((r) => r[2] === email.trim().toLowerCase());
  if (!f) throw new Error(`No employee ${email} in the development credentials file. Run npm run db:reset.`);
  return f[3];
}

/** A mailbox's development password (D30). */
export function mailboxPasswordFor(email: string): string {
  const f = records("mailbox").find((r) => r[1] === email.trim().toLowerCase());
  if (!f) throw new Error(`No development mailbox password for ${email}. Run npm run db:reset.`);
  return f[2];
}

/** The staff member's current TOTP code, and how many seconds it stays valid. */
export function currentTotp(email: string, now = Date.now()): { code: string; secondsLeft: number; organization: string } {
  const staff = readStaffCredential(email);
  const epoch = Math.floor(now / 1000);
  return { code: generateSync({ secret: staff.totpSecret, epoch }), secondsLeft: 30 - (epoch % 30), organization: staff.organization };
}
